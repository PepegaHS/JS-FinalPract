const buildPosts = () => {
    let globalId = 1;
    const all = [];

    const mapTemplate = (temp, cat) => {
        const sources = sourcesList[cat];
        const images = imagesList[cat];
        
        const sourceName = sources[globalId % sources.length];
        const imageUrl = images[globalId % images.length];
        
        const hoursAgo = (globalId * 3) % 48 + 1;
        const date = new Date(Date.now() - hoursAgo * 60 * 60 * 1000).toISOString();

        return {
            id: `post-${globalId++}`,
            title: temp.title,
            description: temp.desc,
            url: `https://example.com/politics-${cat}-${globalId}`,
            urlToImage: imageUrl,
            publishedAt: date,
            source: { name: sourceName },
            category: cat,
            leaning: temp.lean,
            sensationalism: temp.sens
        };
    };

    demTemplates.forEach(t => all.push(mapTemplate(t, "democrats")));
    repTemplates.forEach(t => all.push(mapTemplate(t, "republicans")));
    indTemplates.forEach(t => all.push(mapTemplate(t, "independent")));

    return all;
};

INITIAL_POSTS.push(...buildPosts());

